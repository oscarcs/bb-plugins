// Generates the lightweight stdio ACP proxy that bridges BB runtime directories
// and permission-mode selection (`auto` / `accept-edits`) onto `agy acp --stdio`.

export function renderAgyAcpProxyScript(): string {
  return `// Auto-generated by google-antigravity-acp. Do not edit by hand.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { spawn } from "node:child_process";

const cliCommand = process.env.AGY_CLI_COMMAND || "agy";
const targetMode = (process.env.AGY_ACP_SESSION_MODE || "").trim();
const forwardedArgs = process.argv.slice(2);

function isExistingDir(dirPath) {
  try {
    return fs.statSync(dirPath).isDirectory();
  } catch {
    return false;
  }
}

function getBbAdditionalDirectories() {
  if (process.env.AGY_ACP_DISABLE_BB_DIRS === "1") return [];
  const bbHome = process.env.BB_HOME || path.join(os.homedir(), ".bb");
  const candidates = [
    path.join(bbHome, "runtime", "global-skills"),
    path.join(bbHome, "skills"),
    path.join(bbHome, "skills-generated"),
    path.join(bbHome, "thread-storage"),
    path.join(bbHome, "attachments"),
  ];
  const extra = process.env.AGY_ACP_EXTRA_DIRS;
  if (extra) {
    for (const entry of extra.split(path.delimiter)) {
      const trimmed = entry.trim();
      if (trimmed) candidates.push(trimmed);
    }
  }
  const unique = [];
  for (const candidate of candidates) {
    if (isExistingDir(candidate) && !unique.includes(candidate)) {
      unique.push(candidate);
    }
  }
  return unique;
}

// Only the proxy needs Electron to act as Node.
const childEnv = { ...process.env };
delete childEnv.ELECTRON_RUN_AS_NODE;
const child = spawn(cliCommand, ["acp", "--stdio", ...forwardedArgs], {
  stdio: ["pipe", "pipe", "pipe"],
  env: childEnv,
});

child.stderr.pipe(process.stderr);

// Track client session-setup requests so we can apply AGY_ACP_SESSION_MODE
// after session/new, session/load, or session/resume completes.
const pendingClientSessionReqs = new Map();
// Track internal mode-switch requests keyed by internal JSON-RPC id.
const pendingModeSwitches = new Map();
let internalSeq = 0;

function writeToClient(objOrLine) {
  const line = typeof objOrLine === "string" ? objOrLine : JSON.stringify(objOrLine);
  process.stdout.write(line + "\\n");
}

function writeToChild(objOrLine) {
  const line = typeof objOrLine === "string" ? objOrLine : JSON.stringify(objOrLine);
  try {
    child.stdin.write(line + "\\n");
  } catch {}
}

function mergeAdditionalDirectories(msg) {
  const extraDirs = getBbAdditionalDirectories();
  if (extraDirs.length === 0) return msg;
  const params = msg.params && typeof msg.params === "object" ? { ...msg.params } : {};
  const existing = Array.isArray(params.additionalDirectories)
    ? params.additionalDirectories.filter((d) => typeof d === "string" && d.trim())
    : [];
  const merged = [...existing];
  for (const dir of extraDirs) {
    if (!merged.includes(dir)) merged.push(dir);
  }
  params.additionalDirectories = merged;
  return { ...msg, params };
}

function applyModeToSessionResponse(heldResponse, updatedConfigOptions, appliedMode) {
  const nextResult = { ...(heldResponse.result || {}) };
  if (Array.isArray(updatedConfigOptions)) {
    nextResult.configOptions = updatedConfigOptions;
  }
  if (nextResult.modes && typeof nextResult.modes === "object") {
    nextResult.modes = { ...nextResult.modes, currentModeId: appliedMode };
  }
  return { ...heldResponse, result: nextResult };
}

function sendInternalModeSwitch(sessionId, modeValue, heldResponse, fallbackMode) {
  const internalId = "__bb_agy_mode_" + (++internalSeq);
  pendingModeSwitches.set(internalId, {
    sessionId,
    modeValue,
    heldResponse,
    fallbackMode,
  });
  writeToChild({
    jsonrpc: "2.0",
    id: internalId,
    method: "session/set_config_option",
    params: {
      sessionId,
      configId: "mode",
      value: modeValue,
    },
  });
}

const inRl = readline.createInterface({ input: process.stdin, crlfDelay: Infinity });
inRl.on("line", (line) => {
  let msg = null;
  try {
    msg = JSON.parse(line);
  } catch {}

  if (
    msg &&
    typeof msg === "object" &&
    (msg.method === "session/new" ||
      msg.method === "session/load" ||
      msg.method === "session/resume")
  ) {
    const updated = mergeAdditionalDirectories(msg);
    if (targetMode && msg.id !== undefined && msg.id !== null) {
      const reqSessionId =
        typeof updated.params?.sessionId === "string" ? updated.params.sessionId : null;
      pendingClientSessionReqs.set(String(msg.id), {
        method: msg.method,
        sessionId: reqSessionId,
      });
    }
    writeToChild(updated);
    return;
  }

  writeToChild(line);
});

inRl.on("close", () => {
  try {
    child.stdin.end();
  } catch {}
});

const outRl = readline.createInterface({ input: child.stdout, crlfDelay: Infinity });
outRl.on("line", (line) => {
  let msg = null;
  try {
    msg = JSON.parse(line);
  } catch {}

  if (!msg || typeof msg !== "object") {
    writeToClient(line);
    return;
  }

  // Handle responses to our internal session/set_config_option(mode) call.
  if (msg.id !== undefined && msg.id !== null && pendingModeSwitches.has(msg.id)) {
    const entry = pendingModeSwitches.get(msg.id);
    pendingModeSwitches.delete(msg.id);
    if (!msg.error && msg.result) {
      const updated = applyModeToSessionResponse(
        entry.heldResponse,
        msg.result.configOptions,
        entry.modeValue,
      );
      writeToClient(updated);
      return;
    }
    if (entry.fallbackMode) {
      sendInternalModeSwitch(entry.sessionId, entry.fallbackMode, entry.heldResponse, null);
      return;
    }
    // If mode switch is unsupported (e.g. restricted account), release the original response unchanged.
    writeToClient(entry.heldResponse);
    return;
  }

  // Intercept session/new, session/load, or session/resume response to apply AGY_ACP_SESSION_MODE.
  if (msg.id !== undefined && msg.id !== null && pendingClientSessionReqs.has(String(msg.id))) {
    const reqInfo = pendingClientSessionReqs.get(String(msg.id));
    pendingClientSessionReqs.delete(String(msg.id));
    const sessionId =
      typeof msg.result?.sessionId === "string" ? msg.result.sessionId : reqInfo.sessionId;
    if (!msg.error && msg.result && sessionId && targetMode) {
      const modeOption = Array.isArray(msg.result.configOptions)
        ? msg.result.configOptions.find((c) => c && (c.category === "mode" || c.id === "mode"))
        : null;
      const currentMode = modeOption?.currentValue ?? msg.result.modes?.currentModeId;
      const availableValues = Array.isArray(modeOption?.options)
        ? modeOption.options.map((o) => o && o.value).filter(Boolean)
        : null;
      let chosenMode = targetMode;
      let fallbackMode = targetMode === "auto" ? "accept-edits" : null;
      if (availableValues && availableValues.length > 0 && !availableValues.includes(chosenMode)) {
        if (fallbackMode && availableValues.includes(fallbackMode)) {
          chosenMode = fallbackMode;
          fallbackMode = null;
        } else {
          writeToClient(line);
          return;
        }
      }
      if (currentMode !== chosenMode) {
        sendInternalModeSwitch(sessionId, chosenMode, msg, fallbackMode);
        return;
      }
    }
    writeToClient(line);
    return;
  }

  // Drop intermediate config_option_update emitted while our internal mode switch is in flight.
  if (
    pendingModeSwitches.size > 0 &&
    msg.method === "session/update" &&
    msg.params?.update?.sessionUpdate === "config_option_update"
  ) {
    return;
  }

  writeToClient(line);
});

child.on("error", (err) => {
  process.stderr.write("[google-antigravity-acp proxy] Failed to spawn " + cliCommand + ": " + err.message + "\\n");
  process.exit(1);
});

child.on("exit", (code, signal) => {
  // Flush any held responses if the child died unexpectedly during mode switch.
  for (const entry of pendingModeSwitches.values()) {
    writeToClient(entry.heldResponse);
  }
  pendingModeSwitches.clear();
  if (signal) {
    process.kill(process.pid, signal);
    return;
  }
  process.exit(code ?? 0);
});

for (const sig of ["SIGINT", "SIGTERM"]) {
  process.on(sig, () => {
    try {
      child.kill(sig);
    } catch {}
  });
}
`;
}
